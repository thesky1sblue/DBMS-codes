CREATE TABLE AUTHORS1001(
    AUTHOR_ID INT,
    AUTHNAME VARCHAR2(50),
    EMAIL VARCHAR2(50) NOT NULL UNIQUE,
    CONSTRAINT AUTHOR_IDPK PRIMARY KEY(AUTHOR_ID)
)


CREATE TABLE BOOKS1001(
    ISBN VARCHAR(15),
    B_TITLE VARCHAR(20),
    PRICE NUMBER CHECK (PRICE >0),
    AUTHOR_ID INT,
    CONSTRAINT ISBN_PK PRIMARY KEY(ISBN),
    CONSTRAINT AUTHOR_IDFK FOREIGN KEY (AUTHOR_ID) REFERENCES AUTHORS1001(AUTHOR_ID)
);

